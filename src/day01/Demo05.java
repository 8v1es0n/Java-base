package day01;

public class Demo05 {
    public static void main(String[] args) {
        // 关系运算符
        int a = 10;
        int b = 20;

        System.out.println(a > b);// false
        System.out.println(a < b);// true
        System.out.println(a >= b); // false
        System.out.println(a <= b);// true
        System.out.println(a == b); // false
        System.out.println(a != b); // true
    }
}
