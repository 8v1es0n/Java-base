package day01;

public class Demo04 {
    public static void main(String[] args) {
        int a = 10;
        int b = 3;

        a += b;
        System.out.println(a);

        a -= b;
        System.out.println(a);

        a *= b;
        System.out.println(a);

        a /= b;
        System.out.println(a);
        System.out.println("=========================");
        byte c = 10;
        c += 150;
        System.out.println(c);
    }
}
